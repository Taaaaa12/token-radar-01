// Token Radar, model radar-2: snapshot in, ranked board + dashboard + dossier out.
//
//   node main.ts [--input <snapshot.json or its directory>] [--output <dir>]
//
// The input defaults to /input (the sealed snapshot the grader mounts), the output to
// $MAKEFUN_OUTPUT_DIR or /output. Locally:
//
//   mkdir -p out && MAKEFUN_OUTPUT_DIR=out node main.ts --input ../input/snapshot.json
//
// The run writes, in the output directory:
//   board.json      the ranked board (the gate's rows)
//   data.js         the dashboard's dataset (window.RADAR), no fetch, no network
//   dashboard/      the page, its style and its script, copied from this repository
//   screenshots/    the three dashboard screenshots, copied from this repository
//   dossier.json    buildDossier's dossier of dashboard/ and screenshots/
//
// The run is deterministic: the same snapshot and the same screenshots always write the same bytes.
// It exits 1 when the board fails the gate, 2 when the snapshot cannot be read, 3 when the
// screenshots or the dashboard cannot be copied.

import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-board.ts';
import { boardIssue, buildRadar, dataScript, parseSnapshot } from './lib/model.ts';

const REPO = dirname(fileURLToPath(import.meta.url));

const args = process.argv.slice(2);
function flag(name: string): string | null {
  const i = args.indexOf(name);
  return i >= 0 && i + 1 < args.length ? args[i + 1]! : null;
}

const inputArg = flag('--input') ?? '/input';
const outputDir = resolve(flag('--output') ?? process.env.MAKEFUN_OUTPUT_DIR ?? '/output');
const inputPath = inputArg.endsWith('.json') ? inputArg : join(inputArg, 'snapshot.json');

let snapshotText: string;
try {
  snapshotText = readFileSync(inputPath, 'utf8');
} catch {
  console.error(`token-radar: cannot read the snapshot at ${inputPath}`);
  process.exit(2);
}

let snapshot;
try {
  snapshot = parseSnapshot(snapshotText);
} catch (err) {
  console.error(`token-radar: ${(err as Error).message}`);
  process.exit(2);
}

const { board, radar } = buildRadar(snapshot);
const issue = boardIssue(board, snapshot);
if (issue !== null) {
  console.error(`token-radar: the board fails the gate: ${issue}`);
  process.exit(1);
}

mkdirSync(outputDir, { recursive: true });
mkdirSync(join(outputDir, 'dashboard'), { recursive: true });
mkdirSync(join(outputDir, 'screenshots'), { recursive: true });

// The dashboard, copied whole from this repository (flat: index.html, app.css, app.js).
const dashSrc = join(REPO, 'dashboard');
for (const name of readdirSync(dashSrc).sort()) {
  if (name.startsWith('.')) continue;
  cpSync(join(dashSrc, name), join(outputDir, 'dashboard', name));
}

// The screenshots: three or four whole PNG or JPEG files, each at most 512 KiB, showing this
// dashboard (the board, a protocol's detail view, a filtered view). They are renders of the page,
// taken in a browser, never generated by this program.
const shotsSrc = join(REPO, 'screenshots');
const shotNames = existsSync(shotsSrc)
  ? readdirSync(shotsSrc, { withFileTypes: true }).filter((e) => e.isFile() && !e.name.startsWith('.')).map((e) => e.name).sort()
  : [];
if (shotNames.length < 3) {
  console.error(`token-radar: screenshots/ holds ${shotNames.length} image(s); the dossier needs at least 3 (board, detail, filtered)`);
  process.exit(3);
}
const PNG_MAGIC = [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a];
const JPEG_MAGIC = [0xff, 0xd8, 0xff];
for (const name of shotNames) {
  const bytes = readFileSync(join(shotsSrc, name));
  if (bytes.length > 524288) {
    console.error(`token-radar: screenshots/${name} is ${bytes.length} bytes, over the 512 KiB a screenshot may hold`);
    process.exit(3);
  }
  const isPng = PNG_MAGIC.every((b, i) => bytes[i] === b);
  const isJpeg = JPEG_MAGIC.every((b, i) => bytes[i] === b);
  if (!isPng && !isJpeg) {
    console.error(`token-radar: screenshots/${name} is neither a whole PNG nor a whole JPEG`);
    process.exit(3);
  }
  cpSync(join(shotsSrc, name), join(outputDir, 'screenshots', name));
}

writeFileSync(join(outputDir, 'board.json'), `${JSON.stringify(board, null, 2)}\n`);
writeFileSync(join(outputDir, 'data.js'), dataScript(radar));
writeFileSync(
  join(outputDir, 'dossier.json'),
  buildDossier(outputDir, {
    text_max_bytes: 65536,
    screenshots: { max: 4, max_bytes: 524288 },
    dashboard: { max_files: 400, max_bytes: 4194304 },
  }),
);

const top = board[0]!;
console.log(
  `token-radar radar-2: ${board.length} rows (${radar.watchlist_size} watchlist + ${radar.early_size} early), ` +
    `${radar.live_size} live, top ${top.slug} at $${top.implied_value_usd.toLocaleString('en-US')}, ` +
    `snapshot ${radar.as_of}, wrote ${outputDir}`,
);
